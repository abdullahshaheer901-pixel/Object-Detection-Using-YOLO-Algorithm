import tensorflow as tf
import numpy as np
import cv2
import matplotlib.pyplot as plt

# ------------------------------------------------
# 1.Create Dummy Dataset (Images + Bounding Boxes)
# ------------------------------------------------
# Each label: [x_center, y_center, width, height, class]

IMAGE_SIZE = 128
NUM_CLASSES = 1

def create_dataset(samples=200):
  images =[]
  labels = []

  for _ in range(samples):

      img = np.zeros((IMAGE_SIZE, IMAGE_SIZE, 3), dtype=np.uint8)

      x = np.random.randint(20, 90)
      y = np.random.randint(20, 90)
      w = np.random.randint(20, 40)
      h = np.random.randint(20, 40)

      cv2.rectangle(img, (x,y), (x+w, y+h), (255, 255, 255), -1)

      x_center = (x +w/2) / IMAGE_SIZE
      y_center = (y +h/2) / IMAGE_SIZE
      w = w / IMAGE_SIZE
      h = h / IMAGE_SIZE

      images.append(img/255.0)
      labels.append([x_center, y_center, w, h, 1])

  return np.array(images), np.array(labels)

x, y = create_dataset()

# ------------------------------------------------
# 2. Visualize the Data in Pixel
# ------------------------------------------------
plt.imshow(x[0])
plt.title("Sample Training Image")
plt.axis("off")

plt.tight_layout()
plt.show()

# -----------------------------------
# 3. Train / Test Split
# -----------------------------------

split = int(len(x)*0.8)

x_train, x_test = x[:split], x[split:]
y_train, y_test = y[:split], y[split:]

# -----------------------------------
# 4. Build a YOLO-Like CNN Model
# -----------------------------------

model = tf.keras.Sequential([

    tf.keras.layers.Conv2D(16, (3, 3), activation="relu", input_shape=(IMAGE_SIZE, IMAGE_SIZE, 3)),
    tf.keras.layers.MaxPooling2D(),

    tf.keras.layers.Conv2D(32, (3, 3), activation="relu"),
    tf.keras.layers.MaxPooling2D(),

    tf.keras.layers.Conv2D(64, (3, 3), activation="relu"),
    tf.keras.layers.MaxPooling2D(),

    tf.keras.layers.Flatten(),

    tf.keras.layers.Dense(128, activation='relu'),

    # Output: Bounding box + Class
    tf.keras.layers.Dense(5, activation="sigmoid")
])

model.compile(
    optimizer='adam',
    loss='mse'
)
model.summary()

# -----------------------------------
# 5. Train Model
# -----------------------------------

histroy = model.fit(
    x_train,
    y_train,
    validation_split=0.2,
    epochs=10,
    batch_size=32
)

# -----------------------------------
# 6. Evaluate Model
# -----------------------------------

loss = model.evaluate(x_test, y_test)

print("Test Loss:",loss)

# -----------------------------------
# 7. IoU (Intersection over Union)
# -----------------------------------

def IoU(box1, box2):

  x1, y1, w1, h1 =box1
  x2, y2, w2, h2 =box2

  x1_min = x1 - w1 / 2
  x1_max = x1 + w1 / 2
  y1_min = y1 - h1 / 2
  y1_max = y1 + h1 / 2

  x2_min = x2 - w2 / 2
  x2_max = x2 + w2 / 2
  y2_min = y2 - h2 / 2
  y2_max = y2 + h2 / 2

  inter_xmin = max(x1_min, x2_min)
  inter_ymin = max(y1_min, y2_min)
  inter_xmax = min(x1_max, x2_max)
  inter_ymax = min(y1_max, y2_max)

  inter_area = max(0, inter_xmax - inter_xmin) * max(0, inter_ymax - inter_ymin)

  area1 = w1 *h1
  area2 = w2 *h2

  union = area1 +area2 - inter_area

  return inter_area / union

